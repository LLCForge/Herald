#!/usr/bin/env python3
"""Regenerates data/confusables-compact.txt from the official Unicode TR39 file.

    curl -o confusables.txt https://www.unicode.org/Public/security/latest/confusables.txt
    python -I tools/gen_confusables.py confusables.txt data/confusables-compact.txt

Output: one mapping per line, "<source hex> <target hex> [<target hex> ...]".
Comments and the version header are kept so the provenance is visible.
Standard library only.
"""

import re
import sys

LINE = re.compile(r"^([0-9A-F]{4,6})\s*;\s*([0-9A-F ]+?)\s*;\s*MA\b")


def main(src: str, dst: str) -> int:
    header, rows = [], []
    with open(src, encoding="utf-8-sig") as f:
        for line in f:
            if line.startswith("#") and len(header) < 10:
                if any(k in line for k in ("Date:", "Version:", "©", "terms_of_use")):
                    header.append(line.rstrip("\n"))
                continue
            m = LINE.match(line)
            if m:
                rows.append(f"{m.group(1)} {' '.join(m.group(2).split())}")
    if len(rows) < 5000:
        print(f"only {len(rows)} mappings parsed; refusing to write", file=sys.stderr)
        return 1
    with open(dst, "w", encoding="utf-8", newline="\n") as out:
        out.write("# Compact form of Unicode TR39 confusables.txt (generated by tools/gen_confusables.py).\n")
        for h in header:
            out.write(h + "\n")
        out.write("# Licensed under the Unicode License v3; see NOTICE.\n")
        out.write("\n".join(rows) + "\n")
    print(f"{len(rows)} mappings written to {dst}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        sys.exit(2)
    sys.exit(main(sys.argv[1], sys.argv[2]))
